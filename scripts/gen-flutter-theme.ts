/**
 * Theme tokens for the Flutter app, generated from THEMES / THEME_SWATCH in libs/client/src/charts/palette.ts.
 *
 *   npm run gen:mobile  →  apps/mobile/lib/theme/tokens.g.dart
 *
 * palette.ts is the single source of the chart and surface colors of every theme (palette.spec.ts keeps it in sync with the
 * web stylesheet); the Flutter ThemeData is derived from this file in lib/theme/app_theme.dart.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { FONT_VARS, THEME_IDS, THEME_SWATCH, THEMES } from '../libs/client/src/charts/palette';

const ROOT = process.cwd();
const OUT = join(ROOT, 'apps/mobile/lib/theme/tokens.g.dart');

const camel = (token: string) => token.replace(/^--/, '').replace(/-(\w)/g, (_, c: string) => c.toUpperCase());
const color = (hex: string) => {
  if (!/^#[0-9a-f]{6}$/i.test(hex)) throw new Error(`Unsupported color ${hex}: tokens must be #rrggbb`);
  return `Color(0xFF${hex.slice(1).toUpperCase()})`;
};
const cap = (s: string) => s[0].toUpperCase() + s.slice(1);

const first = THEMES[THEME_IDS[0]];
const tokens = Object.keys(first) as (keyof typeof first)[];
const isSeries = (t: string) => t.startsWith('--series-');
const flat = tokens.filter((t) => !isSeries(t));
const slots = tokens.filter(isSeries);

const lines: string[] = [
  '// GENERATED by scripts/gen-flutter-theme.ts from libs/client/src/charts/palette.ts: do not edit by hand.',
  '// Regenerate with `npm run gen:mobile`.',
  '// ignore_for_file: type=lint',
  '',
  "import 'dart:ui' show Color;",
  '',
  `enum ThemeId { ${THEME_IDS.join(', ')} }`,
  '',
  `const defaultThemeId = ThemeId.${THEME_IDS[0]};`,
  '',
  `const fontSans = ${JSON.stringify(FONT_VARS['--font-sans'])};`,
  `const fontMono = ${JSON.stringify(FONT_VARS['--font-mono'])};`,
  '',
  '/// Colors of one theme: the surface, the chart ink and grid, the money meanings and the eight categorical series.',
  'class ThemeTokens {',
  '  const ThemeTokens({',
  '    required this.accent,',
  ...flat.map((t) => `    required this.${camel(t)},`),
  '    required this.series,',
  '  });',
  '',
  '  /// The theme\'s `--primary`.',
  '  final Color accent;',
  ...flat.map((t) => `  final Color ${camel(t)};`),
  '',
  '  /// Categorical slots, in assignment order.',
  '  final List<Color> series;',
  '}',
  '',
];

for (const id of THEME_IDS) {
  const v = THEMES[id];
  lines.push(`const theme${cap(id)} = ThemeTokens(`, `  accent: ${color(THEME_SWATCH[id].accent)},`);
  for (const t of flat) lines.push(`  ${camel(t)}: ${color(v[t])},`);
  lines.push(`  series: [${slots.map((t) => color(v[t])).join(', ')}],`, ');', '');
}

lines.push('const themeTokens = <ThemeId, ThemeTokens>{', ...THEME_IDS.map((id) => `  ThemeId.${id}: theme${cap(id)},`), '};', '');

mkdirSync(join(OUT, '..'), { recursive: true });
writeFileSync(OUT, lines.join('\n'));
console.log(`theme: ${OUT.replace(`${ROOT}/`, '')}`);
