/**
 * Dart models for the Flutter app, generated from the DTOs in libs/shared/src/dto with quicktype.
 *
 *   npm run gen:mobile  →  apps/mobile/lib/api/models.g.dart
 *
 * quicktype's TypeScript reader cannot take generics, `Record<>` or `Omit<>`, so the DTOs are copied to a temp
 * directory and those three constructs are rewritten first. If a DTO starts using a construct quicktype cannot
 * read, this script fails loudly instead of emitting a partial file.
 */
import { execFileSync } from 'node:child_process';
import { cpSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, relative, resolve } from 'node:path';

const ROOT = process.cwd();
const OUT = join(ROOT, 'apps/mobile/lib/api/models.g.dart');

function tsFiles(dir: string): string[] {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? tsFiles(path) : path.endsWith('.ts') ? [path] : [];
  });
}

/** Members of `interface <name> { … }` (the text between the braces), or `null`. */
function interfaceBody(source: string, name: string): string | null {
  const match = new RegExp(`export interface ${name}\\b[^{]*\\{([\\s\\S]*?)\\n\\}`).exec(source);
  return match ? match[1] : null;
}

/**
 * `interface X extends Omit<Y, 'a' | 'b'> { … }` → `interface X { …Y's members except a and b… }`, so the inherited fields
 * stay in the generated class. `Y` must be declared in the same file.
 */
function inlineOmit(source: string): string {
  return source.replace(/export interface (\w+) extends Omit<(\w+), ([^>]+)> \{/g, (_, name: string, base: string, keys: string) => {
    const body = interfaceBody(source, base);
    if (body === null) throw new Error(`${name} extends Omit<${base}, …>, but ${base} is not declared in the same file`);
    const omitted = [...keys.matchAll(/'(\w+)'/g)].map((m) => m[1]);
    const kept = body.split('\n').filter((line, i, lines) => {
      // a member is `  key: type;` (its doc comment is the lines above it): drop it together with its comment
      const key = /^ {2}(\w+)\??:/.exec(line)?.[1];
      if (key && omitted.includes(key)) return false;
      const next = lines.slice(i + 1).find((l) => /^ {2}\w+\??:/.test(l));
      const isComment = /^ {2}(\/\*\*|\*|\/\/)/.test(line);
      return !(isComment && next && omitted.includes(/^ {2}(\w+)/.exec(next)![1]));
    });
    return `export interface ${name} {${kept.join('\n')}`;
  });
}

/** Rewrites what quicktype's TypeScript reader cannot take. Throws when a pattern it expects is gone. */
export function simplify(source: string): string {
  return inlineOmit(source)
    .replace(/export interface Report<T> \{[\s\S]*?\n\}\n\n/, '')
    .replace(/Record<string, ([\w[\]]+)>/g, '{ [key: string]: $1 }');
}

const work = mkdtempSync(join(tmpdir(), 'spacefly-dto-'));
try {
  const src = join(work, 'src');
  mkdirSync(src);
  cpSync(join(ROOT, 'libs/shared/src/dto'), join(src, 'dto'), { recursive: true });
  cpSync(join(ROOT, 'libs/shared/src/utils'), join(src, 'utils'), { recursive: true });
  const files = tsFiles(join(src, 'dto')).sort();
  for (const file of files) writeFileSync(file, simplify(readFileSync(file, 'utf8')));
  for (const file of files) {
    const text = readFileSync(file, 'utf8');
    if (/\bRecord<|\bOmit<|\bPartial<|\bPick<|interface \w+<|type \w+</.test(text)) throw new Error(`${file}: a construct quicktype cannot read is left; extend simplify() in scripts/gen-flutter-models.ts`);
  }

  const quicktype = join(ROOT, 'node_modules/.bin/quicktype');
  const generated = join(work, 'models.dart');
  execFileSync(quicktype, ['--src-lang', 'typescript', '--lang', 'dart', '--coders-in-class', '-o', generated, ...files.map((f) => relative(work, f))], { cwd: work, stdio: ['ignore', 'inherit', 'inherit'] });

  const header = [
    '// GENERATED by scripts/gen-flutter-models.ts from libs/shared/src/dto: do not edit by hand.',
    '// Regenerate with `npm run gen:mobile`.',
    '// ignore_for_file: type=lint',
    '',
  ].join('\n');
  mkdirSync(join(OUT, '..'), { recursive: true });
  writeFileSync(OUT, header + readFileSync(generated, 'utf8'));
  console.log(`models: ${OUT.replace(`${ROOT}/`, '')}`);
} finally {
  rmSync(work, { recursive: true, force: true });
}
